"""Tests that keep the fallback interface complete.

docs/decisions/0014-one-interface.md (point 4) is why these exist; it is not
restated here. What matters for reading them is the mechanism: the models come
from Django's app registry, never from a list written down in this file,
because a list written down in this file would be the same promise the test
exists to replace.
"""

import datetime
import re
from decimal import Decimal

import pytest
from django.apps import apps
from django.contrib import admin
from django.contrib.auth.models import User
from django.db import models
from django.http import HttpRequest
from django.test import Client, RequestFactory
from django.urls import reverse
from pytest_django.fixtures import Settings
from simple_history.models import HistoricalChanges

from inventory.models import (
    CODE_PATTERN,
    Category,
    Item,
    ItemIdentifier,
    Label,
    Location,
    StockMovement,
    StockTransaction,
    Vendor,
    VendorOffer,
    Volunteer,
)

pytestmark = pytest.mark.django_db


def _needs_admin(model: type[models.Model]) -> bool:
    """Whether ``model`` has to be registered.

    Both exemptions are properties read off the model, so a model qualifies by
    what it *is* rather than by being named in an exception list nobody
    revisits. Anything this app authors and stores has to be registered.
    """
    # Generated by django-simple-history from the model it audits, and already
    # reachable through that model's SimpleHistoryAdmin page.
    if issubclass(model, HistoricalChanges):
        return False
    # A database view owns no rows to administer, and Django refuses to
    # register a model with a composite primary key in any case.
    return model._meta.managed


def _models_needing_admin() -> list[type[models.Model]]:
    return [model for model in apps.get_app_config("inventory").get_models() if _needs_admin(model)]


@pytest.fixture
def administrator_request(rf: RequestFactory, administrator: User) -> HttpRequest:
    request = rf.get("/admin/")
    request.user = administrator
    return request


@pytest.fixture
def _static_files_are_not_collected(settings: Settings) -> None:
    """Serve static files straight from the apps, as a development checkout does.

    Outside DEBUG the project hashes static files through WhiteNoise's manifest
    storage, which is right for the built image -- the image runs collectstatic
    -- and impossible under test, where nothing has. Every admin template opens
    with ``{% static 'admin/css/base.css' %}``, so without this a rendering test
    fails on the manifest rather than on the page. Overridden here rather than in
    settings.py so the deployed behaviour is exactly what it was.
    """
    settings.STORAGES = {
        **settings.STORAGES,
        "staticfiles": {"BACKEND": "django.contrib.staticfiles.storage.StaticFilesStorage"},
    }


@pytest.fixture
def one_of_each_model(
    category: Category,
    item: Item,
    volunteer: Volunteer,
    warehouse: Location,
) -> dict[type[models.Model], models.Model]:
    """One saved row of every model the admin registers, to render a page against.

    A changelist renders its columns only when there is a row to render them
    for, and a change form needs something to change, so an empty database
    would let a stale ``list_display`` or a broken ``__str__`` through. The map
    is checked against the app registry below, so a new model fails the tests
    until it has an example here.
    """
    vendor = Vendor.objects.create(name="Ubiquiti")
    transaction = StockTransaction.objects.create(actor=volunteer, kind=StockTransaction.Kind.RECEIPT)
    return {
        Category: category,
        Item: item,
        ItemIdentifier: ItemIdentifier.objects.create(
            item=item,
            kind=ItemIdentifier.Kind.MFG_PART,
            value="LBE-5AC-GEN2",
        ),
        Label: Label.objects.create(code="ABC2345678", item=item),
        Location: warehouse,
        StockMovement: StockMovement.objects.create(
            transaction=transaction,
            item=item,
            quantity=Decimal("3"),
            to_location=warehouse,
        ),
        StockTransaction: transaction,
        Vendor: vendor,
        VendorOffer: VendorOffer.objects.create(
            item=item,
            vendor=vendor,
            unit_price=Decimal("89.99"),
            observed_at=datetime.date(2026, 1, 6),
        ),
        Volunteer: volunteer,
    }


def test_every_model_is_registered_in_the_admin() -> None:
    unregistered = sorted(model.__name__ for model in _models_needing_admin() if not admin.site.is_registered(model))

    assert not unregistered, (
        f"Not registered in inventory/admin.py: {', '.join(unregistered)}. "
        f"The admin is the fallback that has to stay complete -- see "
        f"docs/decisions/0014-one-interface.md, point 4. If one of these really "
        f"should be left out, the reason belongs in _needs_admin() as a property "
        f"of the model, not as its name."
    )


def test_the_exemptions_are_a_policy_and_not_a_pass() -> None:
    """Guards the test above against passing for the wrong reason.

    A renamed base class or an inverted condition could make ``_exemption``
    excuse every model, and the assertion above would then pass over an empty
    set while proving nothing. Excusing no model at all would mean the
    opposite: two conditions that are dead code claiming to be a policy.
    """
    exempt = [model for model in apps.get_app_config("inventory").get_models() if not _needs_admin(model)]

    assert _models_needing_admin()
    assert exempt


def test_every_registered_model_has_a_row_to_render_its_pages_with(
    one_of_each_model: dict[type[models.Model], models.Model],
) -> None:
    """Guards the two tests below against silently skipping a model."""
    missing = sorted(model.__name__ for model in _models_needing_admin() if model not in one_of_each_model)

    assert not missing, (
        f"No example row in the one_of_each_model fixture for: {', '.join(missing)}. "
        f"Add one, or the admin pages for those models are never rendered by any test."
    )


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_every_changelist_renders(
    editor: Client,
    one_of_each_model: dict[type[models.Model], models.Model],
) -> None:
    """A stale ``list_display`` or a broken ``__str__`` only shows up here.

    Django's admin checks catch a column naming nothing at all; they cannot
    catch a ``ModelAdmin`` method or a ``__str__`` that raises on real data.
    """
    for model in _models_needing_admin():
        url = reverse(f"admin:{model._meta.app_label}_{model._meta.model_name}_changelist")

        response = editor.get(url)

        assert response.status_code == 200, f"{model.__name__} changelist: {url} returned {response.status_code}"


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_every_change_form_renders(
    editor: Client,
    one_of_each_model: dict[type[models.Model], models.Model],
) -> None:
    """Including the ledger's, which renders read-only rather than editable."""
    for model in _models_needing_admin():
        instance = one_of_each_model.get(model)
        # Skipped rather than a KeyError: whether every model has a row is
        # test_every_registered_model_has_a_row_to_render_its_pages_with's to
        # report, and failing here too would bury its message.
        if instance is None:
            continue
        url = reverse(f"admin:{model._meta.app_label}_{model._meta.model_name}_change", args=[instance.pk])

        response = editor.get(url)

        assert response.status_code == 200, f"{model.__name__} change form: {url} returned {response.status_code}"


def test_the_ledger_is_readable_in_the_admin_but_not_editable(administrator_request: HttpRequest) -> None:
    """The ledger admins offer no save button; see inventory/admin.py."""
    for model in (StockTransaction, StockMovement):
        model_admin = admin.site.get_model_admin(model)

        assert model_admin.has_view_permission(administrator_request)
        assert not model_admin.has_change_permission(administrator_request)
        assert not model_admin.has_delete_permission(administrator_request)


def test_a_correction_is_appended_as_a_transaction_not_as_a_loose_movement(
    administrator_request: HttpRequest,
) -> None:
    assert admin.site.get_model_admin(StockTransaction).has_add_permission(administrator_request)
    assert not admin.site.get_model_admin(StockMovement).has_add_permission(administrator_request)


# --------------------------------------------------------------------------
# Labels. The admin is a write path like any other, and the check constraint
# `label_code_is_crockford_base32` holds it to the same format the API mints
# to -- so the form has to be able to satisfy that and to say so when it
# cannot. See LabelAdmin in inventory/admin.py.
# --------------------------------------------------------------------------


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_the_label_add_form_arrives_holding_a_minted_code(editor: Client) -> None:
    """Nobody can invent one: the constraint refuses everything but the format."""
    page = editor.get(reverse("admin:inventory_label_add"))

    minted = page.context["adminform"].form.initial["code"]
    assert re.fullmatch(CODE_PATTERN, minted), minted


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_the_admin_prints_a_label_with_the_code_it_offered(editor: Client, item: Item) -> None:
    minted = editor.get(reverse("admin:inventory_label_add")).context["adminform"].form.initial["code"]

    response = editor.post(
        reverse("admin:inventory_label_add"),
        {"code": minted, "item": item.pk, "quantity": "100"},
    )

    assert response.status_code == 302, response.content
    assert Label.objects.get().code == minted


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_a_code_outside_the_format_is_a_form_error_and_not_an_error_page(editor: Client, item: Item) -> None:
    """The constraint would otherwise surface as an IntegrityError and a 500."""
    response = editor.post(
        reverse("admin:inventory_label_add"),
        {"code": "SHORT", "item": item.pk, "quantity": "1"},
    )

    assert response.status_code == 200
    assert response.context["adminform"].form.errors["code"]
    assert not Label.objects.exists()


@pytest.mark.usefixtures("_static_files_are_not_collected")
def test_a_printed_code_cannot_be_retyped_in_the_admin_either(editor: Client, item: Item) -> None:
    """The sticker is already on a shelf; renaming it would 404 that sticker."""
    label = Label.objects.create(code="ABC2345678", item=item)
    url = reverse("admin:inventory_label_change", args=[label.pk])

    editor.post(url, {"code": "ZZZZZZZZZZ", "item": item.pk, "quantity": "1"})

    label.refresh_from_db()
    assert label.code == "ABC2345678"
